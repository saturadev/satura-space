const FILLED = new Set(['play.fill', 'pause.fill', 'stop.fill', 'bolt.fill', 'forward.frame.fill', 'lock.fill'])

export function Sym({ name, size = 16, stroke = 2.2, fallback = false, className }: { name: string | undefined; size?: number; stroke?: number; fallback?: boolean; className?: string }) {
  const n = name ?? ''
  const digits = /^(\d{1,2})\.circle$/.exec(n)
  if (digits)
    return (
      <span aria-hidden className={`inline-flex shrink-0 items-center justify-center rounded-full border-[1.6px] border-current font-bold leading-none ${className ?? ''}`} style={{ width: size + 2, height: size + 2, fontSize: Math.round(size * 0.62) }}>
        {digits[1]}
      </span>
    )
  const Icon = MAP[n] ?? (fallback ? Circle : null)
  if (!Icon) return null
  return <Icon aria-hidden size={size} strokeWidth={stroke} className={className} fill={FILLED.has(n) ? 'currentColor' : 'none'} />
}

